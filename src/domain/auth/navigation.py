"""Допустимые адреса возврата внутри приложения."""

DEFAULT_NEXT = "/"


def safe_next(raw: str | None) -> str:
    """Куда можно вернуть после входа.

    Только относительный путь внутри этого приложения. Без этой проверки
    маршрут входа — открытый перенаправитель: ссылка
    `…/auth/login?next=https://чужой.сайт` увела бы сотрудника, пришедшего по
    почте, туда, где у него спросят пароль, — и адресная строка до перехода
    выглядела бы безупречно, потому что домен в ней наш.

    Отвергается и `//чужой.сайт`: для браузера это адрес с той же схемой, а не
    путь. Отвергается и обратная косая черта — часть браузеров нормализует её
    в прямую уже после проверки.
    """
    value = (raw or "").strip()
    if not value.startswith("/"):
        return DEFAULT_NEXT
    if value.startswith("//") or value.startswith("/\\"):
        return DEFAULT_NEXT
    return value
